class CatalogEvidenceTests(unittest.TestCase):
    def test_native_material_times_both_bodies(self):
        for number, raw_date, ms, umid in NATIVE:
            with self.subTest(clip=number):
                record = bytearray(160)
                record[0x10:0x18] = bytes.fromhex(raw_date)
                stamp = creation_time(record)
                self.assertEqual(stamp.microsecond, 0)
                expected = bytes.fromhex(umid)[16:23]
                self.assertNotEqual(material_time(stamp), expected)
                self.assertEqual(material_time(stamp + timedelta(milliseconds=ms)), expected)

    def test_literal_native_records_explain_loss_not_acceptance(self):
        for number in MOVIES:
            with self.subTest(clip=number):
                self.assertEqual(len(MOVIES[number]), 160)
                self.assertEqual(len(ARRAY), 160)
                native = next(row for row in NATIVE if row[0] == number)
                result = umid_evidence(MOVIES[number], ARRAY, native[3])
                self.assertFalse(result["exact_match"])
                self.assertTrue(result["non_time_bytes_match"])
                self.assertTrue(result["explained_by_omitted_subseconds"])
                self.assertEqual(result["same_second_material_time_candidates_ms"], [native[2]])
                self.assertFalse(result["camera_acceptance_proven"])

    def test_different_node_is_not_explained_by_time(self):
        native = next(row for row in NATIVE if row[0] == 6502)
        different_node = native[3][:-2] + "00"
        result = umid_evidence(MOVIES[6502], ARRAY, different_node)
        self.assertFalse(result["non_time_bytes_match"])
        self.assertFalse(result["explained_by_omitted_subseconds"])

    def test_wrong_time_is_not_explained(self):
        native = next(row for row in NATIVE if row[0] == 6502)
        bad = bytearray.fromhex(native[3])
        bad[16:20] = bytes(4)
        result = umid_evidence(MOVIES[6502], ARRAY, bad.hex())
        self.assertEqual(result["same_second_material_time_candidates_ms"], [])
        self.assertFalse(result["explained_by_omitted_subseconds"])

    def test_header_time_uses_distinct_packing(self):
        data = bytes.fromhex("002cee64eb070700")
        value = header_time(data, 0)
        self.assertEqual([value[k] for k in ("year", "month", "day", "hour", "minute", "second")],
                         [2026, 11, 12, 19, 46, 11])
        self.assertEqual(value["timezone_minutes"], 480)

    def test_path_cycle_rejected(self):
        raw = bytearray(160)
        raw[4:8] = (1).to_bytes(4, "little")
        row = {"type": 1, "checksum_valid": True, "hex": raw.hex()}
        with self.assertRaisesRegex(ValueError, "cycle"):
            restore_path_template({1: row}, 1)

    def test_path_checksum_required(self):
        with self.assertRaisesRegex(ValueError, "Invalid path"):
            restore_path_template({1: {"type": 1, "checksum_valid": False}}, 1)

    def test_metadata_hash_and_media_mtime_are_separate(self):
        a = {"x": {"sha256": "a", "size": "2", "last_write_time_ns": "1"}}
        b = {"x": {"sha256": "b", "size": "2", "last_write_time_ns": "1"}}
        self.assertEqual(manifest_diff(a, b)["changed"], ["x"])
        self.assertEqual(manifest_diff(a, b, media=True)["changed"], [])


